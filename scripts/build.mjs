import { build } from 'esbuild';
import { mkdir, readdir, rm, copyFile, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
for (const file of await readdir('dist')) if (file.endsWith('.js')) await rm(`dist/${file}`);
const options = { bundle: true, minify: true, format: 'esm', target: 'es2022', outdir: 'dist', splitting: true, entryNames: '[name]-[hash]', chunkNames: 'chunk-[hash]', legalComments: 'eof', metafile: true };
const worker = await build({ ...options, entryPoints: ['src/export-worker.js'] });
const workerPath = Object.entries(worker.metafile.outputs).find(([, info]) => info.entryPoint === 'src/export-worker.js')[0].replace('dist/', '');
const app = await build({ ...options, entryPoints: ['src/app.js'], define: { EXPORT_WORKER_URL: JSON.stringify(workerPath) } });
const appPath = Object.entries(app.metafile.outputs).find(([, info]) => info.entryPoint === 'src/app.js')[0].replace('dist/', '');
let html = await readFile('dist/index.html', 'utf8');
const cssHash = createHash('sha256').update(await readFile('dist/style.css')).digest('hex').slice(0,12);
html = html.replace(/src="app(?:-[A-Z0-9]+)?\.js(?:\?[^\"]*)?"/, `src="${appPath}"`).replace(/href="style\.css(?:\?[^\"]*)?"/, `href="style.css?v=${cssHash}"`).replace(/<span class="beta">.*?<\/span>/, '<span class="beta">v5</span>');
await writeFile('dist/index.html', html);
for (const file of ['file-worker.js', 'download-worker.js']) await copyFile(`src/${file}`, `dist/${file}`);
await mkdir('dist/licenses', { recursive: true });
await copyFile('node_modules/mediabunny/LICENSE', 'dist/licenses/Mediabunny.txt');
await copyFile('node_modules/@mediabunny/aac-encoder/LICENSE', 'dist/licenses/AAC-encoder.txt');
console.log(`Built static GitHub Pages website: ${appPath}, ${workerPath}`);
